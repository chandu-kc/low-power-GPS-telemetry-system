/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */

  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */
  if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE)) {
      __HAL_UART_CLEAR_IDLEFLAG(&huart1);               // Clear IDLE flag
      HAL_UART_DMAStop(&huart1);                         // Stop DMA
      rx_len = RX_BUFFER_SIZE - __HAL_DMA_GET_COUNTER(huart1.hdmarx);  // Calculate received length
      process_uart_data(rx_buffer, rx_len);              // Handle received data
      HAL_UART_Receive_DMA(&huart1, rx_buffer, RX_BUFFER_SIZE);  // Restart DMA
    }

  /* USER CODE END USART1_IRQn 1 */
}

